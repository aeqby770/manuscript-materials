CONFIG <- list(root = Sys.getenv("LLR_WORK_ROOT", unset = getwd()), threads = parallel::detectCores(), prior_count = 2)
Sys.setenv(OMP_NUM_THREADS=CONFIG$threads, OPENBLAS_NUM_THREADS=CONFIG$threads, MKL_NUM_THREADS=CONFIG$threads)
.libPaths(c(file.path(CONFIG$root, "library"), .libPaths()))
library(data.table)
library(edgeR)
setDTthreads(CONFIG$threads)
OUT <- file.path(CONFIG$root, "results/validation/gse291091")
pb <- fread(file.path(OUT, "pseudobulk_counts.csv.gz"))
units <- fread(file.path(OUT, "pseudobulk_samples.csv"))
genes <- pb$gene
pb <- as.matrix(pb[, !"gene"])
rownames(pb) <- genes
prior <- readRDS(file.path(CONFIG$root, "tools/competitors/resources/NicheNet/ligand_target_matrix_nsga2r_final_mouse.rds"))
sample_order <- c("AB_1INJ", "AB_2INJ", "CT_1INJ", "CT_2INJ")
design <- model.matrix(~ factor(c("depleted", "depleted", "control", "control"), levels=c("control", "depleted")))
assignments <- combn(4L, 2L)
contrasts <- matrix(-0.5, nrow=4L, ncol=ncol(assignments))
contrasts[cbind(as.vector(assignments), rep(seq_len(ncol(assignments)), each=2L))] <- 0.5
fwrite(data.table(assignment=seq_len(ncol(assignments)), depleted_sample_1=sample_order[assignments[1,]], depleted_sample_2=sample_order[assignments[2,]], observed=seq_len(ncol(assignments))==1L), file.path(OUT,"sample_assignments.csv"))

mnp <- calcNormFactors(DGEList(pb[, paste("All MNP", sample_order, sep=":")]))
c1qa <- calcNormFactors(DGEList(pb[, paste("C1qa macrophages", sample_order, sep=":")]))
apc <- calcNormFactors(DGEList(pb[, paste("APC", sample_order, sep=":")]))
fap <- calcNormFactors(DGEList(pb[, paste("FAPs", sample_order, sep=":")]))
log_mnp <- cpm(mnp, log=TRUE, prior.count=CONFIG$prior_count)
log_c1qa <- cpm(c1qa, log=TRUE, prior.count=CONFIG$prior_count)
log_apc <- cpm(apc, log=TRUE, prior.count=CONFIG$prior_count)
keep_mnp <- filterByExpr(mnp, design)
keep_c1qa <- filterByExpr(c1qa, design)
keep_apc <- filterByExpr(apc, design)
g1 <- intersect(genes[keep_mnp], rownames(prior))
g2 <- intersect(genes[keep_c1qa], rownames(prior))
g3 <- intersect(genes[keep_apc], rownames(prior))
w1 <- sweep(prior[g1,,drop=FALSE],2,colSums(prior[g1,,drop=FALSE]),"/")
w2 <- sweep(prior[g2,,drop=FALSE],2,colSums(prior[g2,,drop=FALSE]),"/")
w3 <- sweep(prior[g3,,drop=FALSE],2,colSums(prior[g3,,drop=FALSE]),"/")
response1 <- crossprod(w1, abs(log_mnp[g1,,drop=FALSE] %*% contrasts))
response2 <- crossprod(w2, abs(log_c1qa[g2,,drop=FALSE] %*% contrasts))
response3 <- crossprod(w3, abs(log_apc[g3,,drop=FALSE] %*% contrasts))
response <- cbind(response1,response2,response3)
colnames(response) <- paste(rep(c("All MNP","C1qa macrophages","APC"),each=6L),rep(seq_len(6L),times=3L),sep="|")
stopifnot(!any(is.infinite(response)))
fwrite(data.table(ligand=colnames(prior), as.data.table(response)),file.path(OUT,"ligand_target_response_assignments.csv"))
coverage <- data.table(context=c("All MNP","C1qa macrophages","APC"),n_response_genes=c(length(g1),length(g2),length(g3)),n_prior_ligands=ncol(prior),n_biological_samples=4L)
coverage[, n_scored_ligands := c(sum(is.finite(response1[,1])),sum(is.finite(response2[,1])),sum(is.finite(response3[,1])))]
fwrite(coverage,file.path(OUT,"target_program_coverage.csv"))
receptor_response <- cbind(log_mnp %*% contrasts, log_c1qa %*% contrasts, log_apc %*% contrasts)
colnames(receptor_response) <- colnames(response)
fwrite(data.table(gene=genes,as.data.table(receptor_response)),file.path(OUT,"gene_logfc_assignments.csv.gz"))

mnp <- mnp[keep_mnp,,keep.lib.sizes=FALSE]
mnp <- calcNormFactors(mnp)
mnp <- estimateDisp(mnp,design)
fit_mnp <- glmQLFit(mnp,design,robust=TRUE)
de_mnp <- as.data.table(topTags(glmQLFTest(fit_mnp,coef=2),n=Inf)$table,keep.rownames="gene")
de_mnp[,context:="All MNP"]
keep_fap <- filterByExpr(fap,design)
fap <- fap[keep_fap,,keep.lib.sizes=FALSE]
fap <- calcNormFactors(fap)
fap <- estimateDisp(fap,design)
fit_fap <- glmQLFit(fap,design,robust=TRUE)
de_fap <- as.data.table(topTags(glmQLFTest(fit_fap,coef=2),n=Inf)$table,keep.rownames="gene")
de_fap[,context:="FAPs"]
de <- rbindlist(list(de_mnp,de_fap))
de[,`:=`(contrast="depleted minus control at 3dpi",analysis_unit="biological sample pseudobulk",n_per_group=2L)]
fwrite(de,file.path(OUT,"pseudobulk_differential_expression.csv"))
print(coverage)
print(de[gene %in% c("Ccl2","Ccr2","Ly6c2","Mrc1","Csf1r"),.(context,gene,logFC,FDR)])
